#!/usr/bin/env node
// Checks every skill before it ships. No dependencies (Node 18+).
//
//   node scripts/validate.mjs              all checks, live API spec
//   SPEC_FILE=spec.json node scripts/validate.mjs
//   node scripts/validate.mjs --offline    skip the endpoint check
//
// 1. Frontmatter: name = folder, kebab-case; description starts "Use when", <= 1024 chars.
// 2. Workflow skills have the required sections and a samples/ folder (preview mode).
// 3. Every /v1/... path written anywhere exists in the live spec and is not deprecated.
// 4. No real API keys.
// 5. Relative links resolve.
// 6. No scoring math in any doc: describe a score by what it means, never its formula. Reading bands are fine.
import { readFileSync, readdirSync, existsSync, statSync } from 'node:fs'
import { dirname, join, relative, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const SPEC_URL = 'https://api.virlo.ai/openapi.json'
const FOUNDATION = new Set(['virlo-api', 'brand-brief'])
const WORKFLOW_SECTIONS = ['## When to use', '## Workflow', '## Output', '## Rules']
const REAL_KEY = /virlo_tkn_[A-Za-z0-9]{16,}/
const SCORING_MATH = [
  /÷/, /\bln\(/, /\bdivided by\b/i,
  /\s=\s\(?[a-z_0-9]+\)?\s*[\/×*+]\s*\(?[a-z_0-9]/i, // x = a / b
  /\b[a-z]+_[a-z0-9_]+\s?\/\s?\(?[a-z]+_[a-z0-9_]+\b/i, // snake_case / snake_case
  /\bviews\s?\/\s?(?!(hour|day|week|month)\b)\(?[a-z]/i, // views / anything but a time unit
]
const SKIP_DIRS = new Set(['.git', 'node_modules', 'virlo-research', '.github', 'results'])

const problems = []
const fail = (file, msg) => problems.push(`${relative(ROOT, file)}: ${msg}`)

function walk(dir, out = []) {
  for (const name of readdirSync(dir)) {
    if (SKIP_DIRS.has(name)) continue
    const p = join(dir, name)
    if (statSync(p).isDirectory()) walk(p, out)
    else out.push(p)
  }
  return out
}

// Top-level scalar keys only; enough for name/description.
function frontmatter(text) {
  const m = text.replace(/\r\n/g, '\n').match(/^---\n([\s\S]*?)\n---\n/)
  if (!m) return null
  const data = {}
  for (const line of m[1].split('\n')) {
    const kv = line.match(/^([A-Za-z][\w-]*):\s?(.*)$/)
    if (kv) data[kv[1]] = kv[2].replace(/^["']|["']$/g, '').trim()
  }
  return { data, body: text.slice(m[0].length) }
}

async function loadSpec() {
  if (process.env.SPEC_FILE) return JSON.parse(readFileSync(process.env.SPEC_FILE, 'utf8'))
  const res = await fetch(SPEC_URL, { headers: { accept: 'application/json' } })
  if (!res.ok) throw new Error(`GET ${SPEC_URL} -> ${res.status}`)
  return res.json()
}

function routeMatchers(spec) {
  const live = []
  for (const [path, item] of Object.entries(spec.paths ?? {})) {
    for (const [method, op] of Object.entries(item)) {
      if (method === 'parameters' || typeof op !== 'object') continue
      const re = new RegExp('^' + path.replace(/[.*+?^$()|[\]\\]/g, '\\$&').replace(/\\?\{[^}]+\\?\}|\{[^}]+\}/g, '[^/]+') + '$')
      live.push({ method: method.toUpperCase(), path, re, deprecated: !!op.deprecated })
    }
  }
  return live
}

function checkSkills() {
  const dir = join(ROOT, 'skills')
  for (const name of readdirSync(dir)) {
    const folder = join(dir, name)
    if (!statSync(folder).isDirectory()) continue
    const file = join(folder, 'SKILL.md')
    if (!existsSync(file)) {
      fail(folder, 'missing SKILL.md')
      continue
    }
    const fm = frontmatter(readFileSync(file, 'utf8'))
    if (!fm) {
      fail(file, 'no --- frontmatter fences')
      continue
    }
    const { data, body } = fm
    if (data.name !== name) fail(file, `name "${data.name}" must equal the folder "${name}"`)
    if (!/^[a-z0-9]+(-[a-z0-9]+)*$/.test(data.name ?? '')) fail(file, 'name must be lowercase kebab-case')
    if (!data.description) fail(file, 'description is missing')
    else {
      if (data.description.length > 1024) fail(file, `description is ${data.description.length} chars (max 1024)`)
      if (!/^Use when/.test(data.description)) fail(file, 'description must start with "Use when"')
    }
    if (!body.trim()) fail(file, 'body is empty')
    if (!FOUNDATION.has(name)) {
      for (const s of WORKFLOW_SECTIONS) if (!body.includes(s)) fail(file, `missing section "${s}"`)
      if (!body.includes('virlo-api')) fail(file, 'must tell the agent to use the virlo-api skill')
      const samples = join(folder, 'samples')
      if (!existsSync(samples) || !readdirSync(samples).some((f) => f.endsWith('.md'))) fail(folder, 'needs samples/*.md for preview mode')
    }
  }
}

function checkText(files, live) {
  for (const file of files) {
    if (!/\.(md|json|sh|mjs|ya?ml|txt)$/.test(file)) continue
    if (file.endsWith('scripts/validate.mjs')) continue
    const text = readFileSync(file, 'utf8')
    const generated = text.includes('GENERATED by scripts/gen-reference.mjs')
    text.split('\n').forEach((line, i) => {
      const at = `line ${i + 1}`
      if (REAL_KEY.test(line)) fail(file, `${at}: looks like a real API key`)
      if (file.endsWith('.md')) for (const re of SCORING_MATH) if (re.test(line)) fail(file, `${at}: scoring math must not ship (${re}); describe the score by what it means`)
      if (!live || generated || /deprecated/i.test(line)) return
      for (const m of line.matchAll(/(?:\b(GET|POST|PUT|PATCH|DELETE)\s+)?(\/v1\/[A-Za-z0-9_{}\-/]*[A-Za-z0-9_}])/g)) {
        const [, method, raw] = m
        const path = raw.replace(/\/+$/, '')
        const hits = live.filter((r) => r.re.test(path) && (!method || r.method === method))
        if (!hits.length) fail(file, `${at}: ${method ? method + ' ' : ''}${path} is not in the live API spec`)
        else if (hits.every((h) => h.deprecated)) fail(file, `${at}: ${path} is deprecated in the live API spec`)
      }
    })
  }
}

function checkLinks(files) {
  for (const file of files.filter((f) => f.endsWith('.md'))) {
    const text = readFileSync(file, 'utf8').replace(/```[\s\S]*?```/g, '')
    for (const m of text.matchAll(/\]\(([^)\s]+)\)/g)) {
      const target = m[1]
      if (/^(https?:|mailto:|#)/.test(target)) continue
      const p = resolve(dirname(file), target.split('#')[0])
      if (!existsSync(p)) fail(file, `link to ${target} does not resolve`)
    }
  }
}

async function main() {
  const files = walk(ROOT)
  checkSkills()
  let live = null
  if (!process.argv.includes('--offline')) {
    try {
      live = routeMatchers(await loadSpec())
    } catch (e) {
      problems.push(`could not load the API spec (${e.message}); use SPEC_FILE or --offline`)
    }
  }
  checkText(files, live)
  checkLinks(files)
  const skills = readdirSync(join(ROOT, 'skills')).filter((n) => statSync(join(ROOT, 'skills', n)).isDirectory())
  if (problems.length) {
    console.error(problems.map((p) => `✗ ${p}`).join('\n'))
    console.error(`\n${problems.length} problem(s) in ${skills.length} skills.`)
    process.exit(1)
  }
  console.log(`✓ ${skills.length} skills valid${live ? ` (paths checked against ${live.length} live routes)` : ' (endpoint check skipped)'}`)
}

main()
